$divisiMapping = [];
foreach ($sk as $s) {
    // try to find matching class in anggota
    $foundClass = '-';
    $longestMatch = 0;
    
    foreach ($anggota as $a) {
        // fuzzy match
        $sName = strtolower(preg_replace('/[^a-zA-Z0-9]/', '', $s['nama']));
        $aName = strtolower(preg_replace('/[^a-zA-Z0-9]/', '', $a['nama']));
        
        // Check if one contains the other
        if (str_contains($aName, $sName) || str_contains($sName, $aName)) {
            $foundClass = $a['kelas'];
            $s['nama'] = $a['nama']; // Use full name from anggota
            break;
        }
        
        // Or levenshtein
        similar_text($sName, $aName, $percent);
        if ($percent > 85 && $percent > $longestMatch) {
            $longestMatch = $percent;
            $foundClass = $a['kelas'];
            $s['nama'] = $a['nama'];
        }
    }
    
    $divisiMapping[$s['divisi']][] = [
        'nama' => $s['nama'],
        'jabatan' => $s['jabatan'],
        'kelas' => $foundClass
    ];
}

